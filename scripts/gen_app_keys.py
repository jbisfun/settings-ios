#!/usr/bin/env python3
"""Regenerates Sources/Model/AppDataKeys.swift: the UserDefaults keys each port writes
(literal `forKey:` / `@AppStorage` keys; interpolated ones become prefixes). Keys used by more
than one port or by commons are shared settings and never belong to a single app."""
import collections
import glob
import os
import re

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(os.path.dirname(here))  # fossify-ios
pattern = re.compile(r'(?:forKey:\s*|AppStorage\((?:wrappedValue:[^,]+,\s*)?)"((?:[^"\\]|\\.)*)"')


def keys_of(repo):
    keys, prefixes = set(), set()
    for f in glob.glob(os.path.join(root, repo, "Sources", "**", "*.swift"), recursive=True):
        for m in pattern.finditer(open(f, encoding="utf-8").read()):
            k = m.group(1)
            if "\\(" in k:
                p = k.split("\\(")[0]
                if len(p) >= 4:
                    prefixes.add(p)
            elif k and not k.startswith(("Apple", "NS")):
                keys.add(k)
    return keys, prefixes


repos = sorted(os.path.basename(p) for p in glob.glob(os.path.join(root, "*-ios"))
               if os.path.isdir(os.path.join(p, "Sources")) and not p.endswith(("commons-ios", "settings-ios")))
data = {r: keys_of(r) for r in repos}
common, _ = keys_of("commons-ios")
count = collections.Counter(k for ks, _ in data.values() for k in ks)

out = ["// Generated by scripts/gen_app_keys.py; do not edit.", "",
       "extension AppDataSpec {",
       "    /// port -> (UserDefaults keys, key prefixes) only that port writes.",
       "    static let generatedKeys: [String: ([String], [String])] = ["]
for r in repos:
    ks, ps = data[r]
    own = sorted(k for k in ks if count[k] == 1 and k not in common)
    if not own and not ps:
        continue
    q = lambda xs: "[" + ", ".join('"%s"' % x for x in xs) + "]"
    out.append('        "%s": (%s, %s),' % (r, q(own), q(sorted(ps))))
out += ["    ]", "}", ""]
dest = os.path.join(os.path.dirname(here), "Sources", "Model", "AppDataKeys.swift")
os.makedirs(os.path.dirname(dest), exist_ok=True)
open(dest, "w").write("\n".join(out))
print("wrote", dest)
